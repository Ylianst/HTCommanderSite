/* =========================================================================
   HTCommander site — language switcher
   Builds a language dropdown in the nav and links to the equivalent page in
   the chosen language when a translation exists, otherwise to that language's
   home page. Uses only relative paths so it works on the GitHub project
   subpath (ylianst.github.io/HTCommanderSite/).

   Each page must define, before loading this file:
     <script>window.HT_PAGE = { lang: 'en', page: 'index.html', root: '' };</script>
   where:
     lang  = language of the current page ('en', 'es', ...)
     page  = canonical page path relative to a language root
             ('index.html', 'features/aprs.html', ...)
     root  = relative prefix back to the site root
             ''      for /index.html
             '../'   for /features/aprs.html or /es/index.html
             '../../' for /es/features/aprs.html
   ========================================================================= */
(function () {
  "use strict";

  var LANGS = [
    { code: "en", label: "EN", name: "English" },
    { code: "de", label: "DE", name: "Deutsch" },
    { code: "es", label: "ES", name: "Español" },
    { code: "fr", label: "FR", name: "Français" },
    { code: "hi", label: "HI", name: "हिन्दी" },
    { code: "it", label: "IT", name: "Italiano" },
    { code: "ja", label: "JA", name: "日本語" },
    { code: "pl", label: "PL", name: "Polski" },
    { code: "zh", label: "ZH", name: "中文" }
  ];

  /* Non-English languages that a translation exists for, keyed by canonical
     page path. Extend this as pages are translated. 'en' is always available. */
  /* BUILD:TRANSLATED-START — generated by tools/build-i18n.js, do not edit by hand */
  var TRANSLATED = {
    "blog.html": ["de","es","fr","hi","it","ja","pl","zh"],
    "channel-tool.html": ["de","es","fr","hi","it","ja","pl","zh"],
    "downloads.html": ["de","es","fr","hi","it","ja","pl","zh"],
    "feature-gallery.html": ["de","es","fr","hi","it","ja","pl","zh"],
    "features.html": ["de","es","fr","hi","it","ja","pl","zh"],
    "features/address-book.html": ["de","es","fr","hi","it","ja","pl","zh"],
    "features/agwpe.html": ["de","es","fr","hi","it","ja","pl","zh"],
    "features/android-auto.html": ["de","es","fr","hi","it","ja","pl","zh"],
    "features/aprs.html": ["de","es","fr","hi","it","ja","pl","zh"],
    "features/bbs.html": ["de","es","fr","hi","it","ja","pl","zh"],
    "features/bluetooth-audio.html": ["de","es","fr","hi","it","ja","pl","zh"],
    "features/bss.html": ["de","es","fr","hi","it","ja","pl","zh"],
    "features/capture.html": ["de","es","fr","hi","it","ja","pl","zh"],
    "features/channels.html": ["de","es","fr","hi","it","ja","pl","zh"],
    "features/gps.html": ["de","es","fr","hi","it","ja","pl","zh"],
    "features/index.html": ["de","es","fr","hi","it","ja","pl","zh"],
    "features/map.html": ["de","es","fr","hi","it","ja","pl","zh"],
    "features/satellite.html": ["de","es","fr","hi","it","ja","pl","zh"],
    "features/sstv.html": ["de","es","fr","hi","it","ja","pl","zh"],
    "features/terminal.html": ["de","es","fr","hi","it","ja","pl","zh"],
    "features/torrent.html": ["de","es","fr","hi","it","ja","pl","zh"],
    "features/voice.html": ["de","es","fr","hi","it","ja","pl","zh"],
    "features/winlink.html": ["de","es","fr","hi","it","ja","pl","zh"],
    "index.html": ["de","es","fr","hi","it","ja","pl","zh"],
    "license.html": ["de","es","fr","hi","it","ja","pl","zh"],
    "privacy.html": ["de","es","fr","hi","it","ja","pl","zh"],
    "radios.html": ["de","es","fr","hi","it","ja","pl","zh"],
    "screens.html": ["de","es","fr","hi","it","ja","pl","zh"],
    "videos.html": ["de","es","fr","hi","it","ja","pl","zh"]
  };
  /* BUILD:TRANSLATED-END */

  /* Languages that have at least a translated home page (fallback target). */
  var LANG_HOME = ["de", "es", "fr", "hi", "it", "ja", "pl", "zh"];

  var cfg = window.HT_PAGE || { lang: "en", page: "index.html", root: "" };
  var root = cfg.root || "";

  function urlFor(code) {
    if (code === "en") { return root + cfg.page; }
    var avail = TRANSLATED[cfg.page] || [];
    if (avail.indexOf(code) !== -1) { return root + code + "/" + cfg.page; }
    if (LANG_HOME.indexOf(code) !== -1) { return root + code + "/index.html"; }
    return null;
  }

  var host = document.getElementById("langSwitch");
  if (!host) { return; }

  var current = LANGS.filter(function (l) { return l.code === cfg.lang; })[0] || LANGS[0];

  var details = document.createElement("details");
  details.className = "lang";

  var summary = document.createElement("summary");
  summary.className = "lang__btn";
  summary.setAttribute("title", "Choose language");
  summary.setAttribute("aria-label", "Choose language");
  summary.innerHTML =
    '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" ' +
    'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">' +
    '<circle cx="12" cy="12" r="9"/><path d="M3 12h18"/>' +
    '<path d="M12 3a15 15 0 0 1 0 18a15 15 0 0 1 0-18"/></svg>' +
    '<span>' + current.label + "</span>";
  details.appendChild(summary);

  var menu = document.createElement("div");
  menu.className = "lang__menu";

  LANGS.forEach(function (l) {
    var href = urlFor(l.code);
    if (!href) { return; }
    var a = document.createElement("a");
    a.className = "lang__item" + (l.code === cfg.lang ? " is-current" : "");
    a.setAttribute("href", href);
    a.setAttribute("lang", l.code);
    a.setAttribute("hreflang", l.code);
    a.textContent = l.name;
    menu.appendChild(a);
  });

  details.appendChild(menu);
  host.appendChild(details);

  /* Close the dropdown when clicking outside of it. */
  document.addEventListener("click", function (e) {
    if (details.open && !details.contains(e.target)) {
      details.open = false;
    }
  });
})();
